"""Контракты хранения и файловых адаптеров для прикладного слоя."""

from collections.abc import Sequence
from typing import Any, Protocol

from tracereq.domain.entities import (
    HistoryEntry,
    Link,
    Project,
    Requirement,
    RequirementDraft,
    TraceabilityReport,
)
from tracereq.domain.enums import LinkType


class ProjectRepository(Protocol):
    def get(self, project_id: int) -> Project | None: ...
    def list(self) -> list[Project]: ...
    def add(self, name: str, description: str) -> Project: ...
    def update(self, project_id: int, fields: dict[str, Any]) -> Project: ...
    def delete(self, project_id: int) -> None: ...


class RequirementRepository(Protocol):
    def get(self, project_id: int, requirement_id: int) -> Requirement | None: ...
    def list(self, project_id: int) -> list[Requirement]: ...
    def add(self, project_id: int, fields: dict[str, Any]) -> Requirement: ...
    def update(
        self, project_id: int, requirement_id: int, fields: dict[str, Any]
    ) -> Requirement: ...
    def delete(self, requirement_id: int) -> None: ...
    def delete_for_project(self, project_id: int) -> None: ...


class LinkRepository(Protocol):
    def get(self, link_id: int) -> Link | None: ...
    def list_for_project(self, project_id: int) -> list[Link]: ...
    def add(self, source_id: int, target_id: int, link_type: LinkType) -> Link: ...
    def delete(self, link_id: int) -> None: ...
    def delete_for_requirements(self, requirement_ids: Sequence[int]) -> None: ...


class HistoryRepository(Protocol):
    def list(self, requirement_id: int) -> list[HistoryEntry]: ...
    def add(
        self,
        requirement_id: int,
        change_type: str,
        old_values: dict[str, Any] | None,
        new_values: dict[str, Any] | None,
        changed_by: str | None,
    ) -> None: ...
    def delete_for_requirements(self, requirement_ids: Sequence[int]) -> None: ...


class UnitOfWork(Protocol):
    projects: ProjectRepository
    requirements: RequirementRepository
    links: LinkRepository
    history: HistoryRepository

    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class RequirementParser(Protocol):
    def parse(self, file_bytes: bytes) -> list[RequirementDraft]: ...


class ReportExporter(Protocol):
    def export_requirements(self, report: TraceabilityReport) -> bytes: ...
    def export_matrix(self, report: TraceabilityReport) -> bytes: ...
